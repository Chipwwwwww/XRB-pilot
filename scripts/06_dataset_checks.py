"""Step 3c: integrity checks + dataset diagnostic figures. Writes results/data_checks.md and figures/step3_*.png"""
from common import *
from config import *
from plotstyle import *
import numpy as np, pandas as pd

src = pd.read_csv(ROOT/'data/sources.csv')
obs = pd.read_csv(ROOT/'data/observations.csv', dtype={'obs_id': str})
z = np.load(ROOT/'data/processed/features.npz', allow_pickle=False)
rate, err, E = z['rate'], z['err'], z['edges']
acc = obs[obs.in_dataset].reset_index(drop=True)
assert list(acc.obs_id) == list(z['obs_id']), 'feature/obs table misaligned'
order = list(src.source_id); col = source_colors(order)
lab = dict(zip(src.source_id, src.label))
L = ['# Step 3 data checks (auto-generated by scripts/06_dataset_checks.py)', '']
chk = lambda name, ok, detail='': L.append(f'- [{"PASS" if ok else "FAIL"}] {name} {detail}')
chk('unique ObsIDs among accepted', acc.obs_id.is_unique)
chk('ObsID not shared by two sources (all candidates)', obs.groupby('obs_id').source_id.nunique().max() == 1)
chk('labels match source table', all(acc.label == acc.source_id.map(lab)))
chk('y matches label', np.all(z['y'] == (acc.label == 'BH').values))
chk('g matches source_id', np.all(z['source_id'] == acc.source_id.values))
chk('all feature values finite', np.isfinite(rate).all() and np.isfinite(err).all())
chk('all errors > 0', (err > 0).all())
chk('spectrum units = count for all files', set(acc.src_unit) == {'count'}, str(set(acc.src_unit)))
chk('source class TOTAL/COUNT, background TOTAL/COUNT', set(acc.src_class) == {'TOTAL/COUNT'} and set(acc.bkg_class) == {'TOTAL/COUNT'})
chk('BACKSCAL ratio == 1', np.allclose(acc.backscal_ratio, 1))
chk('src and bkg exposure equal', np.allclose(acc.exposure_s, acc.bkg_exposure_s))
chk('pointing header within tolerance', (acc.hdr_sep_deg <= COORD_TOL_DEG).all(), f'max sep {acc.hdr_sep_deg.max():.4f} deg')
chk('all observations in epoch-5 window', acc.mjd.between(MJD_MIN, MJD_MAX).all())
chk('F_5_25 > 0 for shape normalisation', (z['F'] > 0).all(), f'min F = {z["F"].min():.2f} c/s/PCU')
L.append(f'- OBJECT header values per source: ' + '; '.join(f'{s}: {sorted(set(g.object_hdr))}' for s, g in acc.groupby('source_id')))
L.append(f'- Gain drift vs reference EBOUNDS: max {acc.gain_shift_channels.max():.3f} channel (median {acc.gain_shift_channels.median():.3f})')
npos = (rate <= 0)
L.append(f'- Non-positive net bins: {int(npos.sum())} of {npos.size} ({npos.any(1).sum()} observations); '
         'kept as-is (no abs/clip/drop); A uses asinh which is defined for negative values.')
if npos.any():
    L.append('  - affected: ' + ', '.join(f'{o} ({n} bins, >= {E[:-1][r].min():.1f} keV)' for o, n, r in
                                          zip(acc.obs_id[npos.any(1)], npos.sum(1)[npos.any(1)], npos[npos.any(1)])))
pl = z['pl2']; ratio = pl / np.median(pl, 0)
L.append(f'- Response variation (fixed Gamma=2 power law folded through each obs response, per PCU, per grid bin): '
         f'median over bins of the across-obs std = {100*np.median(ratio.std(0)):.2f}%, max bin {100*ratio.std(0).max():.2f}%, '
         f'max single deviation {100*np.abs(ratio-1).max():.2f}%')
L.append(f'- Deadtime (good-xenon lower bound) DTF: median {acc.dtf_xe.median():.4f}, max {acc.dtf_xe.max():.4f}')
L += ['', '## Sample counts per source', '', obs.groupby('source_id').agg(tried=('obs_id', 'size'), accepted=('in_dataset', 'sum'))
      .reindex(order).to_string(), '']
excl = obs[~obs.in_dataset]
L += ['## Excluded candidates', ''] + [f'- {r.obs_id} ({r.source_id}, bin {r.time_bin}): {r.reason}' for r in excl.itertuples()]
(ROOT/'results/data_checks.md').write_text('\n'.join(L), encoding='utf-8')
print('\n'.join(L[:24]))

# ---- figure: per-source diagnostics ----
fig, ax = plt.subplots(2, 3, figsize=(13, 7))
ax = ax.ravel()
cnt = obs.groupby(['source_id', 'in_dataset']).size().unstack(fill_value=0).reindex(order)
ax[0].barh(order, cnt.get(True, 0), color=[CLASS_COLOR[lab[s]] for s in order], label='accepted')
ax[0].barh(order, cnt.get(False, 0), left=cnt.get(True, 0), color=GRID, label='excluded candidate')
ax[0].set_title('observations per source'); ax[0].legend(loc='lower right'); ax[0].invert_yaxis()
for k, (c, t, lg) in enumerate([('exposure_s', 'exposure (s)', False), ('net_rate_5_25', 'net 5-25 keV (count/s/PCU)', True),
                                ('bkg_fraction', 'background / total, 5-25 keV', True), ('net_snr', 'net S/N, 5-25 keV', True),
                                ('hardness_10_25_over_5_10', 'count ratio (10-25)/(5-10) keV', True)], 1):
    for i, s in enumerate(order):
        v = acc.loc[acc.source_id == s, c]
        ax[k].scatter(v, np.full(len(v), i) + np.random.default_rng(i).uniform(-.2, .2, len(v)), s=14,
                      color=CLASS_COLOR[lab[s]], alpha=.8, lw=0)
    ax[k].set_yticks(range(len(order))); ax[k].set_yticklabels(order if k == 3 else []); ax[k].invert_yaxis()
    if lg: ax[k].set_xscale('log')
    ax[k].set_title(t)
ax[3].set_yticklabels(order)
fig.suptitle('Step 3: dataset diagnostics (blue = BH, orange = NS); counts are instrument count rates, not flux', x=0.01, ha='left')
fig.tight_layout(); fig.savefig(ROOT/'figures/step3_dataset_diagnostics.png'); plt.close(fig)

# ---- figure: spectra per source (A: count rate; B: shape) ----
ec = np.sqrt(E[:-1]*E[1:])
fig, ax = plt.subplots(2, 8, figsize=(18, 5.5), sharex=True, sharey='row')
for i, s in enumerate(order):
    m = (acc.source_id == s).values
    for r in rate[m]:
        ax[0, i].plot(ec, np.where(r > 0, r, np.nan), color=CLASS_COLOR[lab[s]], lw=.7, alpha=.6)
        ax[1, i].plot(ec, r/np.sum(r*np.diff(E)), color=CLASS_COLOR[lab[s]], lw=.7, alpha=.6)
    ax[0, i].set_title(f'{s} ({lab[s]}, n={m.sum()})', fontsize=8)
    ax[0, i].set_xscale('log'); ax[0, i].set_yscale('log'); ax[1, i].set_yscale('log')
    ax[1, i].set_xlabel('keV'); ax[1, i].set_xticks([5, 10, 20]); ax[1, i].set_xticklabels(['5', '10', '20']); ax[1, i].xaxis.set_minor_formatter(plt.NullFormatter())
ax[0, 0].set_ylabel('net count/s/keV/PCU'); ax[1, 0].set_ylabel('shape: rate / F(5-25)  [1/keV]')
fig.suptitle('Net count-rate spectra per observation (top: intensity kept; bottom: per-spectrum shape normalised)', x=0.01, ha='left')
fig.tight_layout(); fig.savefig(ROOT/'figures/step3_spectra_by_source.png'); plt.close(fig)

fig, a = plt.subplots(figsize=(7, 3.6))
combos = sorted(acc.pcus.astype(str).unique(), key=lambda c: -(acc.pcus.astype(str) == c).sum())
for i, pc in enumerate(combos):
    m = (acc.pcus.astype(str) == pc).values
    for j, r in enumerate(ratio[m]): a.plot(ec, 100*(r-1), color=SERIES[i], lw=.8, alpha=.7, label=f'PCUs {pc} (n={m.sum()})' if j == 0 else None)
a.set_xscale('log'); a.set_xlabel('keV'); a.set_ylabel('% deviation from median'); a.legend(fontsize=7, ncol=2)
a.set_xticks([5, 10, 20]); a.set_xticklabels(['5', '10', '20']); a.minorticks_off()
a.set_title('Response check: Gamma=2 power law folded through each obs response (per PCU)', loc='left')
tilt = pd.Series(100*(ratio[:, -3]-ratio[:, 2]), index=acc.index)
tt = pd.DataFrame(dict(tilt=tilt, pcus=acc.pcus.astype(str), label=acc.label))
with (ROOT/'results/data_checks.md').open('a', encoding='utf-8') as f:
    f.write('\n\n## Response tilt (% deviation at 22-25 keV minus at 5.5 keV) by PCU combination\n\n')
    f.write(tt.groupby('pcus').tilt.agg(['size', 'mean', 'std']).round(2).to_string())
    f.write('\n\nMean tilt by class: ' + '; '.join(f'{k} {v:.2f}%' for k, v in tt.groupby('label').tilt.mean().items()) + '\n')
fig.savefig(ROOT/'figures/step3_response_variation.png'); plt.close(fig)
progress('3c_dataset_checks', 'results/data_checks.md + step3 figures')
